  UNIQUE KEY `platform_billing_payments_id_company_key` (`id`, `company_id`),
  KEY `platform_billing_payments_company_date_idx` (`company_id`, `payment_date`, `id`),
  KEY `platform_billing_payments_invoice_created_idx` (`invoice_id`, `created_at`),
  CONSTRAINT `platform_billing_payments_amount_chk` CHECK (`amount` > 0),
  CONSTRAINT `platform_billing_payments_company_fkey` FOREIGN KEY (`company_id`) REFERENCES `companies` (`id`) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT `platform_billing_payments_invoice_fkey` FOREIGN KEY (`invoice_id`, `company_id`) REFERENCES `platform_billing_invoices` (`id`, `company_id`) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT `platform_billing_payments_received_by_fkey` FOREIGN KEY (`received_by_id`) REFERENCES `users` (`id`) ON DELETE RESTRICT ON UPDATE RESTRICT
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
